# Implementation of Expectation-Maximization Algorithm

import numpy as np
import matplotlib.pyplot as plt
from sklearn.mixture import GaussianMixture

# Sample dataset
X = np.array([[1], [2], [3], [4], [5], [8], [9], [10], [11], [12]])

# Create EM model
model = GaussianMixture(n_components=2, random_state=42)

# Train model using EM algorithm
model.fit(X)

# Predict clusters
labels = model.predict(X)

# Display results
print("Data:", X.flatten())
print("Cluster Labels:", labels)
print("Cluster Means:", model.means_.flatten())

# Plot clusters
plt.scatter(X, labels, c=labels)
plt.xlabel("Data Values")
plt.ylabel("Cluster")
plt.title("Expectation-Maximization Clustering")
plt.show()