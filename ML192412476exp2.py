import numpy as np
import pandas as pd

def candidate_elimination(data, target):
    # Initialize Specific Boundary (S) with the first positive training instance
    specific_h = data[0].copy()

    # Initialize General Boundary (G) with the most general hypotheses
    general_h = [["?" for _ in range(len(specific_h))] for _ in range(len(specific_h))]

    for i, val in enumerate(data):
        if target[i] == "Yes":
            # For positive instances:
            # If specific hypothesis is too specific, generalize it
            for x in range(len(specific_h)):
                if val[x] != specific_h[x]:
                    specific_h[x] = "?"
                    # Update General boundary elements that are inconsistent
                    for g in general_h:
                        if g[x] != "?" and g[x] != val[x]:
                            general_h.remove(g)
        else:
            # For negative instances:
            # If specific hypothesis matches negative instance, do nothing
            # If general hypothesis is too general, specialize it
            for x in range(len(specific_h)):
                if val[x] != specific_h[x]:
                    for g in general_h:
                        if g[x] == "?":
                            g_new = g.copy()
                            g_new[x] = specific_h[x]
                            if g_new not in general_h:
                                general_h.append(g_new)
                    # Remove hypotheses that are too specific/inconsistent
                    general_h = [g for g in general_h if g[x] != val[x]]

    # Clean up redundant or overly general hypotheses from G
    indices = [i for i, val in enumerate(general_h) if val == ["?" for _ in range(len(specific_h))]]
    for index in sorted(indices, reverse=True):
        general_h.pop(index)

    return list(specific_h), general_h

# Define the training dataset matching the prompt
data_dict = {
    'Sky': ['Sunny', 'Sunny', 'Rainy', 'Sunny'],
    'AirTemp': ['Warm', 'Warm', 'Cold', 'Warm'],
    'Humidity': ['Normal', 'High', 'High', 'High'],
    'Wind': ['Strong', 'Strong', 'Weak', 'Strong'],
    'Water': ['Warm', 'Warm', 'Cool', 'Cool'],
    'Forecast': ['Same', 'Same', 'Change', 'Same'],
    'EnjoySport': ['Yes', 'Yes', 'No', 'Yes']
}

df = pd.DataFrame(data_dict)
X = np.array(df.iloc[:, :-1])
y = np.array(df.iloc[:, -1])

s_boundary, g_boundary = candidate_elimination(X, y)

print("Specific Boundary (S):\n", s_boundary)
print("\nGeneral Boundary (G):\n", g_boundary)